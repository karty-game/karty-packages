const generatedPageMarker = "<!-- Generated by karty-site. -->\n"

func siteFixture() catalog.Master {
	latest := "1.2.3"
	release := func(name, repository, version, digest string) catalog.Version {
		return catalog.Version{
			Version:    version,
			Archive:    "https://github.com/" + repository + "/releases/download/" + name + "-v" + version + "/" + name + "-" + version + ".kpkg",
			SHA256:     strings.Repeat(digest, 64),
			ReleaseURL: "https://github.com/" + repository + "/releases/tag/" + name + "-v" + version,
		}
	}
	return catalog.Master{
		FormatVersion: 1,
		Repository:    "karty-game/karty-packages",
		Packages: []catalog.Package{
			{
				Name: "community-props", Repository: "community/props", Description: "Props maintained outside this repository.",
				Tags: []string{"props", "3d"}, Readme: "https://github.com/community/props/blob/main/README.md",
				Source: "https://github.com/community/props/tree/main", Preview: "https://raw.githubusercontent.com/community/props/main/preview.png",
				Latest:   &latest,
				Versions: []catalog.Version{release("community-props", "community/props", "1.0.0", "b"), release("community-props", "community/props", "1.2.3", "a")},
			},
			{
				Name: "unreleased", Repository: "community/future", Description: "An upcoming package.",
				Tags: []string{"props"}, Readme: "https://github.com/community/future/blob/main/README.md",
				Source: "https://github.com/community/future/tree/main", Versions: []catalog.Version{},
			},
			{
				Name: "controllers", Repository: "karty-game/karty-packages", Description: "Movement and camera helpers.",
				Tags: []string{"input"}, Readme: "https://github.com/karty-game/karty-packages/blob/main/packages/controllers/README.md",
				Source: "https://github.com/karty-game/karty-packages/tree/main/packages/controllers", Latest: &latest,
				Versions: []catalog.Version{release("controllers", "karty-game/karty-packages", "1.2.3", "c")},
			},
		},
	}
}

func masterJSON(t *testing.T, master catalog.Master) []byte {
	t.Helper()
	contents, err := json.MarshalIndent(master, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return contents
}

func readSiteFile(t *testing.T, output, name string) []byte {
	t.Helper()
	contents, err := os.ReadFile(filepath.Join(output, filepath.FromSlash(name)))
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}
	return contents
}

func requireContains(t *testing.T, contents string, fragments ...string) {
	t.Helper()
	for _, fragment := range fragments {
		if !strings.Contains(contents, fragment) {
			t.Errorf("missing %q", fragment)
		}
	}
}

func TestGenerateCompleteSite(t *testing.T) {
	output := filepath.Join(t.TempDir(), "site")
	input := masterJSON(t, siteFixture())
	if err := website.Generate(input, output); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{
		"index.html", "index.md", "packages/controllers.html", "packages/controllers.md",
		"packages/community-props.html", "packages/community-props.md", "packages/unreleased.html", "packages/unreleased.md",
	} {
		contents := readSiteFile(t, output, name)
		if !bytes.HasPrefix(contents, []byte(generatedPageMarker)) {
			t.Errorf("%s is not marked as a generated page", name)
		}
	}
	for _, name := range []string{"assets/theme.css", "assets/catalog.js", "assets/favicon.svg"} {
		if len(readSiteFile(t, output, name)) == 0 {
			t.Errorf("%s is empty", name)
		}
	}
	if contents := readSiteFile(t, output, ".nojekyll"); len(contents) != 0 {
		t.Error(".nojekyll must be empty")
	}
	if contents := readSiteFile(t, output, "master.json"); !bytes.Equal(contents, append(input, '\n')) {
		t.Error("published master.json differs from the supplied catalog")
	}
	index := string(readSiteFile(t, output, "index.html"))
	requireContains(t, index, "assets/theme.css", "assets/catalog.js", "assets/favicon.svg", "packages/controllers.html", "packages/community-props.html", "packages/unreleased.html", "community/props", "3 packages", "2 with published releases")
	if strings.Index(index, "packages/controllers.html") > strings.Index(index, "packages/unreleased.html") {
		t.Error("packages are not sorted by name")
	}
	indexMD := string(readSiteFile(t, output, "index.md"))
	requireContains(t, indexMD, "[Controllers](packages/controllers.md)", "[Community Props](packages/community-props.md)", "Latest: 1.2.3", "No published release yet.")
	detail := string(readSiteFile(t, output, "packages/community-props.html"))
	requireContains(t, detail, "../assets/theme.css", "../assets/catalog.js", "../index.html", "community/props", "https://raw.githubusercontent.com/community/props/main/preview.png", "https://github.com/community/props/blob/main/README.md", "community-props.md", "../master.json")
	detailMD := string(readSiteFile(t, output, "packages/community-props.md"))
	requireContains(t, detailMD, "Repository: community/props", "https://github.com/community/props/blob/main/README.md", "https://github.com/community/props/tree/main", "https://raw.githubusercontent.com/community/props/main/preview.png")
}

func TestGenerateInstallCommandsForEveryPublishedVersion(t *testing.T) {
	output := t.TempDir()
	if err := website.Generate(masterJSON(t, siteFixture()), output); err != nil {
		t.Fatal(err)
	}
	for _, extension := range []string{"html", "md"} {
		t.Run(extension, func(t *testing.T) {
			page := html.UnescapeString(string(readSiteFile(t, output, "packages/community-props."+extension)))
			for _, version := range []struct{ number, digest string }{{"1.2.3", "a"}, {"1.0.0", "b"}} {
				filename := "community-props-" + version.number + ".kpkg"
				requireContains(t, page,
					"curl --fail --location --proto '=https' --proto-redir '=https'",
					"--output '"+filename+"'",
					"'https://github.com/community/props/releases/download/community-props-v"+version.number+"/"+filename+"' &&",
					"printf '%s  %s\\n' '"+strings.Repeat(version.digest, 64)+"' '"+filename+"' | sha256sum --check - &&\nkarty package import '"+filename+"'",
				)
			}
			if strings.Index(page, "community-props-1.2.3.kpkg") > strings.Index(page, "community-props-1.0.0.kpkg") {
				t.Error("older version appears before the latest install command")
			}
			unreleased := string(readSiteFile(t, output, "packages/unreleased."+extension))
			requireContains(t, unreleased, "No published release yet.", "No published versions.")
			for _, fragment := range []string{"curl --", "sha256sum", "karty package import", "unreleased-0."} {
				if strings.Contains(unreleased, fragment) {
					t.Errorf("unreleased package advertises an install: %q", fragment)
				}
			}
		})
	}
}

func TestGenerateEscapesDescriptions(t *testing.T) {
	master := siteFixture()
	master.Packages[0].Description = `<script>alert("unsafe")</script> [download](javascript:alert(1)) *bold*` + "\nsecond line"
	output := t.TempDir()
	if err := website.Generate(masterJSON(t, master), output); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"index.html", "packages/community-props.html"} {
		page := string(readSiteFile(t, output, name))
		if strings.Contains(page, `<script>alert(`) {
			t.Errorf("%s contains executable description markup", name)
		}
		requireContains(t, page, "&lt;script&gt;alert(", "&lt;/script&gt;")
	}
	for _, name := range []string{"index.md", "packages/community-props.md"} {
		page := string(readSiteFile(t, output, name))
		requireContains(t, page, "&lt;script&gt;", `\[download\](javascript:alert(1))`, `\*bold\* second line`)
		if strings.Contains(page, `<script>`) || strings.Contains(page, `[download](javascript:`) {
			t.Errorf("%s contains unescaped description markup", name)
		}
	}
}

func TestGenerateRejectsInvalidCatalogBeforeWriting(t *testing.T) {
	cases := map[string]func(*catalog.Master){
		"unsupported format":           func(m *catalog.Master) { m.FormatVersion = 2 },
		"missing packages":             func(m *catalog.Master) { m.Packages = nil },
		"repository traversal":         func(m *catalog.Master) { m.Repository = "../outside" },
		"package repository traversal": func(m *catalog.Master) { m.Packages[0].Repository = "owner/.." },
		"name traversal":               func(m *catalog.Master) { m.Packages[0].Name = "../outside" },
		"name path":                    func(m *catalog.Master) { m.Packages[0].Name = "nested/package" },
		"invalid name":                 func(m *catalog.Master) { m.Packages[0].Name = "Bad Name" },
		"duplicate name":               func(m *catalog.Master) { m.Packages = append(m.Packages, m.Packages[0]) },
		"empty description":            func(m *catalog.Master) { m.Packages[0].Description = " \n" },
		"unsafe readme":                func(m *catalog.Master) { m.Packages[0].Readme = "javascript:alert(1)" },
		"unsafe source":                func(m *catalog.Master) { m.Packages[0].Source = "http://github.com/community/props" },
		"unsafe preview":               func(m *catalog.Master) { m.Packages[0].Preview = "data:image/svg+xml,unsafe" },
		"credentials in archive": func(m *catalog.Master) {
			m.Packages[0].Versions[0].Archive = "https://user:pass@example.com/package.kpkg"
		},
		"unsafe archive":       func(m *catalog.Master) { m.Packages[0].Versions[0].Archive = "javascript:package.kpkg" },
		"archive query":        func(m *catalog.Master) { m.Packages[0].Versions[0].Archive += "?download=1" },
		"not an archive":       func(m *catalog.Master) { m.Packages[0].Versions[0].Archive = "https://example.com/package.zip" },
		"unsafe release link":  func(m *catalog.Master) { m.Packages[0].Versions[0].ReleaseURL = "file:///release" },
		"short digest":         func(m *catalog.Master) { m.Packages[0].Versions[0].SHA256 = "abc" },
		"nonhex digest":        func(m *catalog.Master) { m.Packages[0].Versions[0].SHA256 = strings.Repeat("z", 64) },
		"uppercase digest":     func(m *catalog.Master) { m.Packages[0].Versions[0].SHA256 = strings.Repeat("A", 64) },
		"noncanonical version": func(m *catalog.Master) { m.Packages[0].Versions[0].Version = "1.0" },
		"prefixed version":     func(m *catalog.Master) { m.Packages[0].Versions[0].Version = "v1.0.0" },
		"version traversal":    func(m *catalog.Master) { m.Packages[0].Versions[0].Version = "../outside" },
		"duplicate version": func(m *catalog.Master) {
			m.Packages[0].Versions = append(m.Packages[0].Versions, m.Packages[0].Versions[0])
		},
		"missing latest":          func(m *catalog.Master) { m.Packages[0].Latest = nil },
		"unknown latest":          func(m *catalog.Master) { value := "9.0.0"; m.Packages[0].Latest = &value },
		"older latest":            func(m *catalog.Master) { value := "1.0.0"; m.Packages[0].Latest = &value },
		"latest without versions": func(m *catalog.Master) { m.Packages[0].Versions = nil },
		"invalid tag":             func(m *catalog.Master) { m.Packages[0].Tags = []string{"../outside"} },
		"duplicate tag":           func(m *catalog.Master) { m.Packages[0].Tags = []string{"props", "props"} },
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			master := siteFixture()
			mutate(&master)
			output := filepath.Join(t.TempDir(), "not-created")
			if err := website.Generate(masterJSON(t, master), output); err == nil {
				t.Fatal("invalid catalog accepted")
			}
			if _, err := os.Lstat(output); !os.IsNotExist(err) {
				t.Fatalf("invalid catalog modified output: %v", err)
			}
		})
	}
	for name, contents := range map[string][]byte{
		"malformed":         []byte(`{"format_version":`),
		"unknown field":     []byte(`{"format_version":1,"repository":"owner/repo","packages":[],"extra":true}`),
		"trailing document": append(masterJSON(t, siteFixture()), []byte(` {}`)...),
		"oversized":         bytes.Repeat([]byte(" "), website.MaximumMasterBytes+1),
	} {
		t.Run(name, func(t *testing.T) {
			if err := website.Generate(contents, filepath.Join(t.TempDir(), "site")); err == nil {
				t.Fatal("invalid JSON accepted")
			}
		})
	}
}

func snapshotSite(t *testing.T, output string) map[string]string {
	t.Helper()
	result := make(map[string]string)
	if err := filepath.WalkDir(output, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		name, err := filepath.Rel(output, path)
		if err != nil {
			return err
		}
		contents, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		result[filepath.ToSlash(name)] = string(contents)
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	return result
}

func TestGenerateIsDeterministic(t *testing.T) {
	input := masterJSON(t, siteFixture())
	output := t.TempDir()
	if err := website.Generate(input, output); err != nil {
		t.Fatal(err)
	}
	before := snapshotSite(t, output)
	if err := website.Generate(input, output); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(before, snapshotSite(t, output)) {
		t.Error("regeneration changed output bytes or file set")
	}
	other := t.TempDir()
	if err := website.Generate(input, other); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(before, snapshotSite(t, other)) {
		t.Error("output depends on destination directory")
	}
}

func TestGeneratePrunesOnlyOwnedPackagePages(t *testing.T) {
	master := siteFixture()
	output := t.TempDir()
	if err := website.Generate(masterJSON(t, master), output); err != nil {
		t.Fatal(err)
	}
	unrelated := map[string]string{
		"keep.txt": "keep root file", "packages/notes.txt": "keep notes",
		"packages/handwritten.html": "<!doctype html><p>Keep handwritten page</p>",
		"packages/handwritten.md":   "# Keep handwritten Markdown\n", "assets/custom.css": "/* keep custom asset */",
	}
	for name, contents := range unrelated {
		if err := os.WriteFile(filepath.Join(output, filepath.FromSlash(name)), []byte(contents), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	master.Packages = master.Packages[:2]
	if err := website.Generate(masterJSON(t, master), output); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"packages/controllers.html", "packages/controllers.md"} {
		if _, err := os.Stat(filepath.Join(output, name)); !os.IsNotExist(err) {
			t.Errorf("stale generated page %s remains: %v", name, err)
		}
	}
	for name, expected := range unrelated {
		if contents := string(readSiteFile(t, output, name)); contents != expected {
			t.Errorf("unrelated file %s changed", name)
		}
	}
	if index := string(readSiteFile(t, output, "index.html")); strings.Contains(index, "packages/controllers.html") {
		t.Error("pruned package remains in index")
	}
}

func TestGenerateRejectsSymlinkOutputRoot(t *testing.T) {
	outside := t.TempDir()
	if err := os.WriteFile(filepath.Join(outside, "index.html"), []byte("existing source"), 0o600); err != nil {
		t.Fatal(err)
	}
	before := snapshotSite(t, outside)
	output := filepath.Join(t.TempDir(), "site")
	if err := os.Symlink(outside, output); err != nil {
		t.Fatal(err)
	}
	if err := website.Generate(masterJSON(t, siteFixture()), output); err == nil {
		t.Error("accepted symlink as output root")
	}
	if !reflect.DeepEqual(before, snapshotSite(t, outside)) {
		t.Error("generation modified files through output-root symlink")
	}
}

func TestGenerateConfinesWritesAndPruningToOutputRoot(t *testing.T) {
	for _, name := range []string{"assets", "packages", "index.html", "packages/stale.html"} {
		t.Run(name, func(t *testing.T) {
			output := t.TempDir()
			outside := t.TempDir()
			if err := os.WriteFile(filepath.Join(outside, "sentinel.html"), []byte(generatedPageMarker+"keep outside page"), 0o600); err != nil {
				t.Fatal(err)
			}
			before := snapshotSite(t, outside)
			if err := os.MkdirAll(filepath.Dir(filepath.Join(output, name)), 0o755); err != nil {
				t.Fatal(err)
			}
			target := outside
			if strings.HasSuffix(name, ".html") {
				target = filepath.Join(outside, "sentinel.html")
			}
			if err := os.Symlink(target, filepath.Join(output, name)); err != nil {
				t.Fatal(err)
			}
			if err := website.Generate(masterJSON(t, siteFixture()), output); err == nil {
				t.Error("accepted output symlink escaping the root")
			}
			if !reflect.DeepEqual(before, snapshotSite(t, outside)) {
				t.Error("generation changed files outside the output root")
			}
		})
	}
}
